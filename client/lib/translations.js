// Look up a nested key path like "home.aboutLabel" in the given language,
// falling back to English, then to the key itself so a miss never crashes.
export function translate(lang, path) {
  const dig = (dict) => path.split('.').reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), dict)
  return dig(translations[lang]) ?? dig(translations.en) ?? path
}
